      expect(items.first.createdAt.isUtc, isTrue);
      expect(items.last.isRead, isTrue);
      expect(items.last.route, isNull);
    });

    test('a notification with no readable created_at is skipped', () {
      final page = parsePagedEnvelope(
        {
          'items': [
            {...apiFixtureItems('notifications', 'page').first},
            {
              ...apiFixtureItems('notifications', 'page').last,
              'created_at': null,
            },
          ],
          'next_cursor': null,
          'has_more': false,
        },
        NotificationModel.fromJson,
        label: 'notifications',
      );

      // A row dated at the epoch would sort and read wrong with no sign of it.
      expect(page.items.map((n) => n.id), ['n-1']);
    });

    test('reads the unread count of every page from its own route', () async {
      final api = RecordingApi(
        (options) => ok(apiFixture('notifications', 'unread_count')),
