      expect(data.realtime!.provider, 'supabase');
      expect(data.realtime!.channel, 'flatmates:user:7');
      expect(data.realtime!.privateChannel, isTrue);
      // The list the backend serves is the list the app subscribes to.
      expect(data.realtime!.events, [
        'new_match',
        'new_message',
        'conversation_updated',
        'visit_updated',
        'listing_status_changed',
        'new_notification',
      ]);
    });

    test('a new user has a profile with only an id', () {
      final data = BootstrapData.fromJson(
        apiFixture('bootstrap', 'bootstrap_new_user'),
      );

