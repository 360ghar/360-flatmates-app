    test('a message or a like with no readable created_at is skipped', () {
      // A row stamped with the current time or the epoch would sort and read
      // wrong with no sign of it.
      List<T> parse<T>(
        List<Map<String, dynamic>> items,
        T Function(Map<String, dynamic>) fromJson,
      ) => parsePagedEnvelope(
        {
          'items': [
            for (final item in items) {...item, 'created_at': 'not a date'},
          ],
          'next_cursor': null,
          'has_more': false,
        },
        fromJson,
        label: 'rows',
      ).items;

      expect(
        parse(
          apiFixtureItems('conversations', 'messages_page'),
          ChatMessage.fromJson,
        ),
        isEmpty,
      );
      expect(
        parse(
          apiFixtureItems('likes', 'incoming_page'),
          IncomingLikeModel.fromJson,
        ),
        isEmpty,
      );
      expect(
        parse(
          apiFixtureItems('likes', 'outgoing_page'),
          OutgoingLikeModel.fromJson,
        ),
        isEmpty,
      );
    });

