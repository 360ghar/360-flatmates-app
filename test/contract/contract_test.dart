void main() {
  group('Bootstrap', () {
    test('parses profile, catalogs, counts and realtime config', () {
      final data = BootstrapData.fromJson(apiFixture('bootstrap', 'bootstrap'));

      expect(data.profile.id, 7);
      expect(data.profile.fullName, 'Asha Verma');
